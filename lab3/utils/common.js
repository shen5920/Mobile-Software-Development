// 获取新闻列表（可传入分类名进行筛选）
function getNewsList(category) {
  let list = [];
  for (var i = 0; i < news.length; i++) {
    if (category && news[i].category != category) {
      continue;
    }
    let obj = {};
    obj.id = news[i].id;
    obj.poster = news[i].poster;
    obj.add_date = news[i].add_date;
    obj.title = news[i].title;
    obj.category = news[i].category;
    list.push(obj);
  }
  return list; // 返回新闻列表
}

// 获取轮播图列表（传入分类名筛选，只返回有图新闻）
function getSwiperList(category) {
  let list = [];
  for (var i = 0; i < news.length; i++) {
    if (category && news[i].category != category) {
      continue;
    }
    if (!news[i].poster) {
      continue; // 无图新闻不进轮播
    }
    let obj = {};
    obj.id = news[i].id;
    obj.src = news[i].poster;
    obj.title = news[i].title;
    list.push(obj);
  }
  return list;
}

// 搜索新闻（按标题关键词，跨分类搜索）
function searchNews(keyword) {
  let list = [];
  for (var i = 0; i < news.length; i++) {
    if (news[i].title.indexOf(keyword) >= 0) {
      let obj = {};
      obj.id = news[i].id;
      obj.poster = news[i].poster;
      obj.add_date = news[i].add_date;
      obj.title = news[i].title;
      obj.category = news[i].category;
      list.push(obj);
    }
  }
  return list;
}

// 获取新闻内容
function getNewsDetail(newsID) {
  let msg = {
    code: '404', // 没有对应的新闻
    news: {}
  };
  for (var i = 0; i < news.length; i++) {
    if (newsID == news[i].id) { // 匹配新闻id编号
      msg.code = '200'; // 成功
      msg.news = news[i]; // 更新当前新闻内容
      break;
    }
  }
  return msg; // 返回查找结果
}

